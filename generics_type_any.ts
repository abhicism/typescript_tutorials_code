/*

the any type means TypeScript stops checking the type of that variable.
 You can store anything in it: numbers, strings, booleans, objects, arrays, etc.
*/

let data : any;
//for number
data= 100;
console.log(data);
//for string
data= "abhishek";
console.log(data);
//for boolean
data= true;
console.log(data);
//for array
data= [1,2,3,4,5];
console.log(data);
//for object
data= {
    name:"abhishek",
    age:20
};
console.log(data);
